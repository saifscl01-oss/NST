"""``python -m fmfc_research <command>`` — read-only local research toolkit.

Commands:
  discover   Find FM/FIFA installations under given roots (and Steam libraries).
  inventory  SHA-256 inventory + layout classification of one installation -> evidence bundle.
  compare    Diff two inventory.json files (e.g. two builds or two editions).
  rea-plan   Print the REA commands (docs/REVERSE_ENGINEERING_TOOLING.md) for an installation's key binaries.
  verify     Check an evidence bundle against its manifest.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .compare import compare_inventories
from .discovery import classify, discover, steam_library_roots
from .inventory import build_inventory, summarize
from .report import EvidenceBundle, inventory_markdown, verify_bundle


def _cmd_discover(a: argparse.Namespace) -> int:
    roots = [Path(r) for r in a.roots]
    if a.steam:
        roots += steam_library_roots(Path(a.steam))
    found = [i.to_dict() for i in discover(roots, max_depth=a.depth)]
    print(json.dumps({"roots": [str(r) for r in roots], "installations": found}, indent=2))
    return 0


def _cmd_inventory(a: argparse.Namespace) -> int:
    root = Path(a.root)
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2
    bundle = EvidenceBundle(Path(a.out), [root], label=a.label or root.name)
    inst = classify(root).to_dict()
    max_bytes = None if a.max_hash_mb is None else a.max_hash_mb * 1024 * 1024

    def progress(i: int, p: Path) -> None:
        if not a.quiet and i % 500 == 0:
            print(f"  hashed {i} files ... {p.name}", file=sys.stderr)

    entries = build_inventory(root, max_hash_bytes=max_bytes, workers=a.workers, progress=progress)
    summary = summarize(entries)
    bundle.write_json("inventory.json", {"root": str(root), "label": bundle.label,
                                         "entries": [e.to_dict() for e in entries]})
    bundle.write_json("classification.json", inst)
    bundle.write_json("summary.json", summary)
    key = {e.path: e.sha256 for e in entries if e.path in set(inst["key_files"])}
    bundle.write_json("key_binaries.json", key)
    bundle.write_text("report.md", inventory_markdown(f"Inventory: {bundle.label}", str(root), summary, [inst]))
    manifest = bundle.finalize()
    print(f"evidence bundle written: {manifest.parent}")
    return 0


def _cmd_compare(a: argparse.Namespace) -> int:
    left = json.loads(Path(a.left).read_text(encoding="utf-8"))
    right = json.loads(Path(a.right).read_text(encoding="utf-8"))
    diff = compare_inventories(left["entries"], right["entries"]).to_dict()
    diff["left"] = left.get("label")
    diff["right"] = right.get("label")
    text = json.dumps(diff, indent=2)
    if a.out:
        Path(a.out).write_text(text + "\n", encoding="utf-8")
    print(json.dumps(diff["summary"]) if a.out else text)
    return 0


def _cmd_rea_plan(a: argparse.Namespace) -> int:
    """Emit REA commands copied from the audited templates; this tool never runs them."""
    root = Path(a.root)
    inst = classify(root)
    out = a.evidence_dir
    lines = ["# Generated by fmfc_research rea-plan. Review, then run in PowerShell. Read-only commands only.",
             f"# Installation: {root}  games={inst.games} layouts={inst.layouts}",
             f'rea inspect-desktop-application "{root}" --detail summary --evidence_output "{out}\\desktop.json" --json']
    for rel in inst.key_files:
        p = root / rel
        stem = Path(rel).name.replace(".", "_")
        if rel.lower().endswith("global-metadata.dat"):
            ga = root / "GameAssembly.dll"
            lines.append(f'rea inspect-il2cpp-metadata "{p}" --binary "{ga}" --detail summary '
                         f'--evidence_output "{out}\\{stem}-linked.json" --json')
            continue
        for cmd in ("inspect-pe-imports", "inspect-pe-certificates", "inspect-pe-resources"):
            lines.append(f'rea {cmd} "{p}" --max-file-bytes 536870912 --json | '
                         f'Set-Content -Encoding utf8 "{out}\\{stem}-{cmd}.json"')
        lines.append(f'rea inspect-native-exports "{p}" --detail summary --evidence_output "{out}\\{stem}-exports.json" --json')
    print("\n".join(lines))
    return 0


def _cmd_verify(a: argparse.Namespace) -> int:
    problems = verify_bundle(Path(a.bundle))
    print("OK" if not problems else "\n".join(problems))
    return 0 if not problems else 1


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="fmfc-research", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    d = sub.add_parser("discover")
    d.add_argument("roots", nargs="*", default=[])
    d.add_argument("--steam", help="Steam install dir, e.g. 'C:\\Program Files (x86)\\Steam'")
    d.add_argument("--depth", type=int, default=4)
    d.set_defaults(fn=_cmd_discover)
    i = sub.add_parser("inventory")
    i.add_argument("root")
    i.add_argument("--out", required=True, help="evidence bundle directory (must be outside the installation)")
    i.add_argument("--label")
    i.add_argument("--max-hash-mb", type=int, default=None, help="skip hashing files larger than this")
    i.add_argument("--workers", type=int, default=4)
    i.add_argument("--quiet", action="store_true")
    i.set_defaults(fn=_cmd_inventory)
    c = sub.add_parser("compare")
    c.add_argument("left")
    c.add_argument("right")
    c.add_argument("--out")
    c.set_defaults(fn=_cmd_compare)
    r = sub.add_parser("rea-plan")
    r.add_argument("root")
    r.add_argument("--evidence-dir", default="C:\\re\\out")
    r.set_defaults(fn=_cmd_rea_plan)
    v = sub.add_parser("verify")
    v.add_argument("bundle")
    v.set_defaults(fn=_cmd_verify)
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return int(args.fn(args))


if __name__ == "__main__":
    sys.exit(main())
